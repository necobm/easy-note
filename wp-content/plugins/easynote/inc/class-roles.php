/**
 * Role / capability helpers.
 *
 * @package EasyNote
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Owns the `easynote_note` capability set and the admin/owner distinction.
 *
 * Under the headless model there is no user confinement: wp-admin stays stock.
 * These helpers exist only to grant the note capabilities on activation and to
 * answer "can this user manage notes that aren't theirs?" for REST ownership
 * filtering. A lone administrator receives the full set and owns everything.
 */
final class EasyNote_Roles {

	/** Capability that marks a full site administrator. */
	const ADMIN_CAP = 'manage_options';

	/**
	 * Primitive capabilities generated by the note post type's `capability_type`.
	 *
	 * Meta capabilities (singular, e.g. `edit_easynote_note`) are resolved from
	 * these by `map_meta_cap`, so only the primitive (plural) caps are granted.
	 *
	 * @return string[]
	 */
	public static function note_caps() {
		return array(
			'edit_easynote_notes',
			'edit_others_easynote_notes',
			'edit_published_easynote_notes',
			'edit_private_easynote_notes',
			'publish_easynote_notes',
			'read_private_easynote_notes',
			'delete_easynote_notes',
			'delete_others_easynote_notes',
			'delete_published_easynote_notes',
			'delete_private_easynote_notes',
		);
	}

	/**
	 * No runtime hooks needed; the helpers below are static.
	 */
	public function register() {}

	/**
	 * Grant the full note capability set to a role.
	 *
	 * Idempotent: WP_Role::add_cap() no-ops when the cap is already present.
	 *
	 * @param string $role_name Role slug (e.g. 'administrator').
	 */
	public static function grant_caps( $role_name ) {
		$role = get_role( $role_name );

		if ( null === $role ) {
			return;
		}

		foreach ( self::note_caps() as $cap ) {
			$role->add_cap( $cap );
		}
	}

	/**
	 * Is the current user a full site administrator?
	 *
	 * @return bool
	 */
	public static function is_site_admin() {
		return current_user_can( self::ADMIN_CAP );
	}

	/**
	 * May the current user read/edit notes owned by other users?
	 *
	 * Used by the REST layer to decide whether note listings are scoped to the
	 * current user or span the whole workspace.
	 *
	 * @return bool
	 */
	public static function can_manage_others_notes() {
		return current_user_can( 'edit_others_easynote_notes' );
	}
}
